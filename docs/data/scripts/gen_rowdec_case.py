# m68k_alu_rowdec as an exhaustive table on ird[15:3], generated from the dump (sim/dump_rowdec.cpp) of the term module written
# by gen_alu_rowdec.py; the dump is docs/data/mc68000_alu_rowdec_dump.txt. Same function by construction (check: rowdec bench
# with the independent model + a second dump equal to the first).
# Usage: python gen_rowdec_case.py <dump.txt> <output .sv>
import sys
# License header written at the top of every generated file (the same text as in the hand-written sources).
LICENSE_HEADER = ('// This file is part of rm68000, an MC68000 core in SystemVerilog.\n'
                  '// Copyright (c) 2026 Umberto Parisi (rmonic79)\n'
                  '//\n'
                  '// rm68000 is free software: you can redistribute it and/or modify it under the terms of the GNU General Public\n'
                  '// License as published by the Free Software Foundation, either version 3 of the License, or (at your option) any\n'
                  '// later version. It is distributed in the hope that it will be useful, but WITHOUT ANY WARRANTY; without even the\n'
                  '// implied warranty of MERCHANTABILITY or FITNESS FOR A PARTICULAR PURPOSE. See the GNU General Public License for\n'
                  '// more details: LICENSE in the root of the repository, or <https://www.gnu.org/licenses/>.\n'
                  '//\n'
                  '// A commercial license, for use without the obligations of the GPL (for example in closed-source products), is\n'
                  '// available from the author, who can also be contacted for other licensing needs.\n'
                  '\n')
dump, out = sys.argv[1], sys.argv[2]
T = {}
for l in open(dump):
    a, row, cc, rn = l.split(); T[int(a, 16)] = (int(row), int(cc), int(rn, 16))
assert len(T) == 65536
for a in range(65536): assert T[a] == T[a & ~7], f'ird[2:0] enters the decoder: {a:04x}'   # only ird[15:3]
DEF = (0, 0, 0x7fff)
rows = [(a >> 3, T[a]) for a in range(0, 65536, 8) if T[a] != DEF]
nl = '\n'
with open(out, 'w', newline=nl) as f:
    f.write(LICENSE_HEADER)
    f.write('// m68k_alu_rowdec.sv - row decoder of the ALU matrix (FIG. 18) as an exhaustive table on ird[15:3] (ird[2:0] is not an input).' + nl)
    f.write('// GENERATED by gen_rowdec_case.py from docs/data/mc68000_alu_rowdec_dump.txt, the dump of the 45-term module of gen_alu_rowdec.py: same function by construction.' + nl)
    f.write("// Outputs: row = row 1..15 (0 = none), cc_inh = An destination (PSW not updated), row_n = negated one-hot (not used in the core)." + nl)
    f.write('module m68k_alu_rowdec (' + nl + '  /* verilator lint_off UNUSEDSIGNAL */' + nl + '  input  logic [15:0] ird,' + nl + '  /* verilator lint_on UNUSEDSIGNAL */' + nl)
    f.write('  output logic [14:0] row_n,' + nl + '  output logic [3:0]  row,' + nl + '  output logic        cc_inh' + nl + ');' + nl)
    f.write('  always_comb begin' + nl + "    row_n = 15'h7fff; row = 4'd0; cc_inh = 1'b0;" + nl + '    case (ird[15:3])' + nl)
    for k, (row, cc, rn) in rows:
        f.write(f"      13'd{k}: begin row = 4'd{row}; cc_inh = 1'b{cc}; row_n = 15'h{rn:04x}; end" + nl)
    f.write('      default: ;' + nl + '    endcase' + nl + '  end' + nl + 'endmodule' + nl)
print(f'{len(rows)} non-default entries out of 8192 (ird[15:3]); distinct values {len(set(v for _, v in rows))}')
